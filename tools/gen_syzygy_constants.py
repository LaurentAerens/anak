#!/usr/bin/env python3
"""
Generates src/Anak.Data/Syzygy/SyzygyConstants.cs from the reference tables published by
python-chess (chess.syzygy, itself a port of Ronald de Man's tbprobe.c).

Only the immutable lookup tables are emitted. Derived tables (PAWNIDX, PFACTOR, binomials)
are computed at startup in C# so they stay trivially auditable.

Usage:  .venv\\Scripts\\python.exe tools\\gen_syzygy_constants.py
"""
from pathlib import Path

import chess.syzygy as sz

OUT = Path(__file__).resolve().parent.parent / "src" / "Anak.Data" / "Syzygy" / "SyzygyConstants.cs"


def fmt_1d(name: str, values, per_line: int = 16) -> str:
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("        " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    return f"    public static readonly int[] {name} =\n    [\n" + "\n".join(lines) + "\n    ];\n"


def fmt_2d(name: str, rows, per_line: int = 16) -> str:
    out = [f"    public static readonly int[][] {name} =\n    [\n"]
    for row in rows:
        out.append("        [\n")
        for i in range(0, len(row), per_line):
            out.append("            " + ", ".join(str(v) for v in row[i:i + per_line]) + ",\n")
        out.append("        ],\n")
    out.append("    ];\n")
    return "".join(out)


def main() -> None:
    parts = [
        "// <auto-generated>\n",
        "// Generated by tools/gen_syzygy_constants.py from python-chess chess.syzygy. Do not edit by hand.\n",
        "// </auto-generated>\n",
        "namespace Anak.Data.Syzygy;\n\n",
        "/// <summary>\n",
        "/// Immutable index-mapping tables used by the Syzygy (Ronald de Man) position encoder.\n",
        "/// </summary>\n",
        "internal static class SyzygyConstants\n{\n",
        fmt_1d("Triangle", sz.TRIANGLE),
        "\n", fmt_1d("InvTriangle", sz.INVTRIANGLE),
        "\n", fmt_1d("Lower", sz.LOWER),
        "\n", fmt_1d("Diag", sz.DIAG),
        "\n", fmt_1d("Flap", sz.FLAP),
        "\n", fmt_1d("PTwist", sz.PTWIST),
        "\n", fmt_1d("InvFlap", sz.INVFLAP),
        "\n", fmt_1d("FileToFile", sz.FILE_TO_FILE),
        "\n", fmt_1d("MTwist", sz.MTWIST),
        "\n", fmt_2d("KkIdx", sz.KK_IDX),
        "\n", fmt_2d("PpIdx", sz.PP_IDX),
        "\n", fmt_1d("WdlToMap", sz.WDL_TO_MAP),
        "\n", fmt_1d("PaFlags", sz.PA_FLAGS),
        "\n", fmt_1d("WdlToDtz", sz.WDL_TO_DTZ),
        "}\n",
    ]
    OUT.write_text("".join(parts), encoding="utf-8", newline="\n")
    print(f"Wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
